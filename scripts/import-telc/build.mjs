/**
 * telc B1 + Einbürgerungstest importer (TELC-001).
 *
 *   node scripts/import-telc/build.mjs                 # write both courses into content/ + loaders
 *   node scripts/import-telc/build.mjs --only vocab --out /tmp/x   # one module, to a scratch dir
 *
 * Each module exports `build()` → array of `unit()` bundles (see lib.mjs). Validate the
 * output with: TELC_OUT=<dir> npx vitest run --config scripts/import-telc/vitest.config.mts
 */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib.mjs";

const TELC_ID = "telc-b1-en-de";
const EB_ID = "einbuergerung-en-de";

/** Module name → [course, import path]. Order = path order in the course. */
const MODULES = [
  ["overview", TELC_ID, "./telc/overview.mjs"],
  ["vocab", TELC_ID, "./telc/vocab.mjs"],
  ["grammar", TELC_ID, "./telc/grammar.mjs"],
  ["reading", TELC_ID, "./telc/reading.mjs"],
  ["bausteine", TELC_ID, "./telc/bausteine.mjs"],
  ["listening", TELC_ID, "./telc/listening.mjs"],
  ["writing", TELC_ID, "./telc/writing.mjs"],
  ["speaking", TELC_ID, "./telc/speaking.mjs"],
  ["mock", TELC_ID, "./telc/mock.mjs"],
  ["einbuergerung", EB_ID, "./einbuergerung.mjs"],
];

const COURSES = {
  [TELC_ID]: {
    id: TELC_ID,
    title: "telc B1 Exam Prep",
    learningLanguage: "de",
    knownLanguage: "en",
    version: 2,
    // TELC-003: A1/A2 vocabulary for learners who need the basics first; B1 = the exam.
    levels: [
      {
        level: "A1",
        title: "A1 · Basics",
        description: "Basic vocabulary: numbers, family, food, home, key verbs.",
      },
      {
        level: "A2",
        title: "A2 · Everyday",
        description: "Everyday vocabulary: work, travel, shopping, feelings, the Perfekt.",
      },
      {
        level: "B1",
        title: "B1 · telc exam",
        description: "B1 vocabulary, grammar and every part of the telc Deutsch B1 exam.",
      },
    ],
  },
  [EB_ID]: {
    id: EB_ID,
    title: "Einbürgerungstest",
    learningLanguage: "de",
    knownLanguage: "en",
    version: 1,
  },
};

const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? undefined : args[i + 1];
};
const only = opt("only")?.split(",");
const outDir = opt("out");
const contentDir = outDir ?? join(ROOT, "content", "courses");

const bundlesByCourse = { [TELC_ID]: [], [EB_ID]: [] };
for (const [name, courseId, path] of MODULES) {
  if (only && !only.includes(name)) continue;
  let mod;
  try {
    mod = await import(path);
  } catch (error) {
    if (error.code === "ERR_MODULE_NOT_FOUND" && !only) {
      console.warn(`skip ${name}: module not written yet`);
      continue;
    }
    throw error;
  }
  const bundles = await mod.build();
  for (const b of bundles)
    for (const l of b.lessons)
      if (l.courseId !== courseId) throw new Error(`${l.id}: courseId ${l.courseId} ≠ ${courseId}`);
  bundlesByCourse[courseId].push(...bundles);
  const lessons = bundles.reduce((n, b) => n + b.lessons.length, 0);
  const exercises = bundles.reduce(
    (n, b) => n + b.lessons.reduce((m, l) => m + l.exercises.length, 0),
    0,
  );
  console.log(`${name}: ${bundles.length} units, ${lessons} lessons, ${exercises} exercises`);
}

// Units must be grouped by CEFR level in order (ADR-008). Stable sort: within a level the
// module order stays (the exam overview opens B1, before the B1 vocabulary).
const CEFR = ["A1", "A2", "B1", "B2", "C1", "C2"];
for (const bundles of Object.values(bundlesByCourse)) {
  bundles.sort((a, b) => CEFR.indexOf(a.unit.level ?? "") - CEFR.indexOf(b.unit.level ?? ""));
}

const loaders = {};
for (const [courseId, bundles] of Object.entries(bundlesByCourse)) {
  if (bundles.length === 0) continue;
  const dir = join(contentDir, courseId);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, "lessons"), { recursive: true });
  const course = { ...COURSES[courseId], units: bundles.map((b) => b.unit) };
  writeFileSync(join(dir, "course.json"), `${JSON.stringify(course, null, 2)}\n`);
  for (const b of bundles) {
    for (const l of b.lessons) {
      writeFileSync(join(dir, "lessons", `${l.id}.json`), `${JSON.stringify(l, null, 2)}\n`);
    }
  }
  loaders[courseId] = bundles.flatMap((b) => b.lessons.map((l) => l.id));
}

if (!outDir && !only) {
  // Generated loader map for src/lib/content/bundled-content.ts (one chunk per lesson).
  const lines = [
    "// GENERATED by scripts/import-telc/build.mjs (TELC-001). Do not edit by hand.",
    'import type { JsonLoader } from "./bundled-content";',
    "",
    "const json =",
    "  (load: () => Promise<{ default: unknown }>): JsonLoader =>",
    "  () =>",
    "    load().then((module) => module.default);",
    "",
  ];
  for (const [courseId, ids] of Object.entries(loaders)) {
    const name = courseId === TELC_ID ? "TELC_B1_LESSON_LOADERS" : "EINBUERGERUNG_LESSON_LOADERS";
    lines.push(`export const ${name}: Readonly<Record<string, JsonLoader>> = {`);
    for (const id of ids) {
      lines.push(
        `  "${id}": json(() => import("../../../content/courses/${courseId}/lessons/${id}.json")),`,
      );
    }
    lines.push("};", "");
  }
  writeFileSync(join(ROOT, "src", "lib", "content", "generated-exam-loaders.ts"), lines.join("\n"));
}
console.log(`written to ${contentDir}`);
