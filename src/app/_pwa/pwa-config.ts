/** Shared PWA constants (PLT-002), used by the manifest, layout metadata and tests. */
// Relative JSON import on purpose: `next.config.ts` loads this file (no `@/` alias there).
import enEsCourse from "../../../content/courses/en-es/course.json";

export const ICONS = {
  any192: "/icons/icon-192.png",
  any512: "/icons/icon-512.png",
  maskable512: "/icons/icon-maskable-512.png",
  apple180: "/apple-touch-icon.png",
  /** Served by the `app/icon.svg` metadata route. */
  favicon: "/icon.svg",
} as const;

/** Route served when a navigation isn't cached and the network is down. */
export const OFFLINE_FALLBACK_URL = "/offline";

/** Service worker URL and scope (Serwist `swDest` is `public/sw.js`). */
export const SW_URL = "/sw.js";
export const SW_SCOPE = "/";

/**
 * The prerendered `/lesson/<id>` pages of the bundled course (PLT-007 criterion 7), so a
 * lesson opens offline even on a cold start. Read straight from the manifest; the unit
 * test checks it against the schema-validated `bundledLessonPaths` from `@/lib/content`.
 */
export const LESSON_ROUTES: readonly string[] = enEsCourse.units.flatMap((unit) =>
  unit.lessons.map((lesson) => `/lesson/${encodeURIComponent(lesson.id)}`),
);

/**
 * App-shell URLs precached by the service worker (criterion 6), in addition to the
 * build's JS/CSS chunks and `public/` files (icons) that Serwist adds itself: the static
 * (prerendered) routes plus the manifest and favicon generated by Next.js metadata routes.
 */
export const PRECACHED_ROUTES = [
  "/",
  "/profile",
  "/onboarding",
  OFFLINE_FALLBACK_URL,
  "/manifest.webmanifest",
  ICONS.favicon,
  ...LESSON_ROUTES,
];

/** Supabase REST/Auth/Realtime/Storage path prefixes (hosted and `supabase start`). */
const SUPABASE_PATH = /^\/(?:auth|rest|realtime|storage|functions|graphql)\/v1\//;

/**
 * Requests to Supabase are never cached by the service worker (ARCHITECTURE §10): the
 * sync engine owns retries, and auth/session responses must never be served stale.
 */
export function isSupabaseRequest(url: URL): boolean {
  return url.hostname.endsWith(".supabase.co") || SUPABASE_PATH.test(url.pathname);
}
